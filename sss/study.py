"""Portable instructions and copyable, evidence-based study tasks."""

from importlib.resources import files
from pathlib import Path

GENERATED = "<!-- Generated by S.S.S; personal notes belong in notes/. -->\n\n"
CATALOG = (
    ("course-guide", "课程学习指南", "教材、考核、重点与时间投入", "course-guide.md"),
    ("assessment-scan", "字幕中的考核与安排", "查考试、评分、实验、签到和截止", "assessment-scan.md"),
    ("exam-plan", "考前复习", "范围核实、题型练习与自测", "exam-plan.md"),
    ("assignment-lab", "作业与实验清单", "要求、提交、验收与易漏事项", "assignment-lab.md"),
    ("chapter-tutor", "知识点辅导", "循序讲解、例题与相近练习", "chapter-tutor.md"),
    ("study-update", "同步后的学习更新", "新安排、更正与待核实事项", "study-update.md"),
)


def resource(name):
    return files("sss").joinpath("study_resources", name).read_text(encoding="utf-8").strip()


def prompt_catalog(plan=None, root=None):
    context = "请在这门课的本地资料目录中完成以下学习任务。"
    if plan:
        term = plan["term"].get("name") or plan["term"]["id"]
        teachers = "、".join(plan.get("teachers", [])) or "待核实"
        context = f"课程：{plan['code']} · {plan['name']}；学期：{term}；本班教师：{teachers}。"
    context += f"\n课程目录：`{Path(root).resolve()}`。" if root is not None else "\n以下路径均相对于当前课程目录。"
    common = resource("prompt-rules.md")
    return [{"id": key, "title": title, "description": description,
             "text": f"{context}\n\n{common}\n\n{resource(filename)}"}
            for key, title, description, filename in CATALOG]


def prompts_markdown(plan=None):
    text = "# 学习提示词\n\n在 AI 中打开或附上这门课的目录，再复制以下任一完整提示词。首次使用建议选“课程学习指南”。\n"
    for item in prompt_catalog(plan):
        text += f"\n## {item['title']}\n\n{item['description']}\n\n```text\n{item['text']}\n```\n"
    return text


def write_study_files(store, root, plan):
    values = {
        "code": plan["code"], "name": plan["name"],
        "term": str(plan["term"].get("name") or plan["term"]["id"]),
        "teachers": "、".join(plan.get("teachers", [])) or "待核实",
    }
    instructions = resource("agent-guide.md")
    for key, value in values.items():
        instructions = instructions.replace("{{" + key + "}}", value)
    documents = {
        "AGENTS.md": instructions,
        "CLAUDE.md": "# 课程学习入口\n\n请先完整读取同目录的 `AGENTS.md`，遵循其中的学习约定，再按 `README.md` 和 `SCHEMA.md` 定位材料。具体任务可参考 `PROMPTS.md`。本文件不另设一套规则。",
        "SCHEMA.md": resource("schema.md"),
        "PROMPTS.md": prompts_markdown(plan),
    }
    for name, text in documents.items():
        path = Path(root) / name
        if path.exists() and not path.read_text(encoding="utf-8").startswith(GENERATED):
            continue
        store.text(path, GENERATED + text.rstrip() + "\n")
